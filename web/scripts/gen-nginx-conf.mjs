#!/usr/bin/env node
// Renders deploy/nginx/wallet.noc-tura.io.conf from deploy/security-headers.mjs.
//
// Generated rather than hand-written because the headers exist in two places — the file
// nginx serves and the tests that assert them — and hand-keeping two copies in step is
// exactly the job that stops being done. `--check` re-renders and diffs, so a hand edit to
// the served file that skipped the source fails CI instead of drifting quietly.
//
// This produces a server block to install, not something that deploys itself. Installing
// it, obtaining the certificate and reloading nginx are steps a person takes on the VPS.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {SECURITY_HEADERS, CACHE_RULES, OMITTED} from '../deploy/security-headers.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT_PATH = resolve(HERE, '../deploy/nginx/wallet.noc-tura.io.conf');

const HOST = 'wallet.noc-tura.io';
const ROOT = '/var/www/wallet.noc-tura.io';
const COORDINATOR = 'https://api.noc-tura.io';

const wrap = (text, width, indent) => {
  const out = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line && `${line} ${word}`.length > width) {
      out.push(indent + line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) out.push(indent + line);
  return out.join('\n');
};

/** `always` on every add_header: without it nginx drops the header on 4xx and 5xx. */
const headerLines = (indent = '    ') =>
  SECURITY_HEADERS.map(
    h => `${wrap(`# ${h.why}`, 92, `${indent}# `).replace(`${indent}# # `, `${indent}# `)}\n` +
      `${indent}add_header ${h.name} "${h.value}" always;`,
  ).join('\n\n');

/**
 * Cache-Control is chosen by a `map`, not by `add_header` inside a location — and that is not
 * a style preference. nginx's add_header does not merge: ONE add_header anywhere in a location
 * block discards every add_header inherited from the server block. A per-location cache header
 * would therefore have served /assets/ with no CSP, no HSTS and no Permissions-Policy, and
 * nothing would have complained. A map keeps every header at server level, where it is
 * inherited by everything, and an empty value makes nginx emit nothing at all — which is what
 * the proxied paths want, so the coordinator's own Cache-Control passes through untouched.
 */
const cacheMap = () => {
  const rows = [
    ...CACHE_RULES.filter(r => r.match.endsWith('/')).map(r => [`"~^${r.match}"`, r.value]),
    ...CACHE_RULES.filter(r => !r.match.endsWith('/')).map(r => [`"${r.match}"`, r.value]),
    ['"~^/(api/|rpc$)"', ''],
  ];
  const width = Math.max(...rows.map(([k]) => k.length), 'default'.length);
  return [
    `    default${' '.repeat(width - 'default'.length)}  "no-cache";`,
    ...rows.map(([k, v]) => `    ${k}${' '.repeat(width - k.length)}  "${v}";`),
  ].join('\n');
};

export function render() {
  return `# ${HOST} — generated by scripts/gen-nginx-conf.mjs from deploy/security-headers.mjs.
# DO NOT EDIT THIS FILE. Edit the source and re-run the generator; \`npm run nginx:check\`
# fails on a hand edit.
#
# Separate server block, separate origin (§6.5): separate storage, separate cookies, and a
# policy that never has to accommodate the marketing site's needs. It shares a machine with
# the coordinator, which is the known single-host risk in §8 — the wallet goes down when the
# API does. Accepted for S0 in exchange for /api and /rpc being genuinely same-origin, which
# is what lets connect-src stay at 'self' and removes CORS from the picture entirely.

# Cache-Control lives here rather than in the locations it applies to. nginx's add_header does
# not merge: a single add_header inside a location DISCARDS every add_header inherited from the
# server block, so a Cache-Control on /assets/ would have quietly served the bundle with no CSP
# and no HSTS. An empty value makes nginx emit nothing, which is what the proxied paths want —
# the coordinator's own Cache-Control then passes through unchanged.
map $uri $noctura_cache_control {
${cacheMap()}
}

server {
    listen 80;
    listen [::]:80;
    server_name ${HOST};

    # ACME stays reachable over plain HTTP; everything else is redirected before it can
    # carry anything. The redirect is 301 so the HSTS header below is reached once and then
    # the browser stops using http:// on its own.
    location ^~ /.well-known/acme-challenge/ { root /var/www/certbot; }
    location / { return 301 https://$host$request_uri; }
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${HOST};

    ssl_certificate     /etc/letsencrypt/live/${HOST}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${HOST}/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;
    ssl_session_timeout 1d;
    ssl_session_cache   shared:WalletSSL:10m;
    ssl_session_tickets off;

    # OCSP stapling: the browser gets the revocation answer with the handshake instead of
    # asking the CA, which is both faster and one fewer party learning who visits.
    ssl_stapling on;
    ssl_stapling_verify on;

    root ${ROOT};
    index index.html;

    # The bundle is public and the machine is shared; nothing here should announce the
    # version of the thing serving it.
    server_tokens off;

${headerLines()}

    add_header Cache-Control $noctura_cache_control always;

    # ${OMITTED.map(o => `${o.name} is deliberately absent: ${o.why}`).join('\n    # ')}

    # The coordinator, same-origin from the browser's point of view. proxy_ssl_server_name
    # is required or the TLS handshake to the upstream goes out without SNI and lands on the
    # wrong vhost. The Origin is set here rather than forwarded: it is what the coordinator
    # allowlists, and a browser-supplied value is not a control anyway (§6.6).
    location /api/ {
        proxy_pass ${COORDINATOR}/api/;
        proxy_ssl_server_name on;
        proxy_set_header Host api.noc-tura.io;
        proxy_set_header Origin https://${HOST};
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_http_version 1.1;
        proxy_read_timeout 30s;

        # The upstream sets its own CORS headers for browsers arriving directly. Arriving
        # through here the request is same-origin, so those headers are noise at best and a
        # second, contradictory answer at worst.
        proxy_hide_header Access-Control-Allow-Origin;
        proxy_hide_header Access-Control-Allow-Credentials;
    }

    # /rpc is a single method-allowlisted endpoint, not a prefix. Exact-match location so
    # nothing else can be reached through it, and no trailing path is passed upstream.
    location = /rpc {
        proxy_pass ${COORDINATOR}/api/v1/rpc;
        proxy_ssl_server_name on;
        proxy_set_header Host api.noc-tura.io;
        proxy_set_header Origin https://${HOST};
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_http_version 1.1;
        proxy_read_timeout 30s;
        proxy_hide_header Access-Control-Allow-Origin;
        proxy_hide_header Access-Control-Allow-Credentials;
    }

    # No SPA fallback on purpose. S0 has no client-side router (verified: no pushState, no
    # useLocation, no path reading anywhere in web/src), so every real URL is a real file.
    # A blanket try_files $uri /index.html would answer 200 for every typo and every probe,
    # which makes a mistyped link look like a working page and hides scanning in the logs.
    location / {
        try_files $uri $uri/ =404;
    }
}
`;
}

function main() {
  const check = process.argv.includes('--check');
  const rendered = render();

  if (!check) {
    mkdirSync(dirname(OUT_PATH), {recursive: true});
    writeFileSync(OUT_PATH, rendered);
    console.log(`wrote ${OUT_PATH}`);
    return;
  }

  let onDisk;
  try {
    onDisk = readFileSync(OUT_PATH, 'utf8');
  } catch {
    console.error(`MISSING ${OUT_PATH} — run \`npm run nginx\``);
    process.exit(2);
  }
  if (onDisk !== rendered) {
    console.error(
      `STALE ${OUT_PATH}\nThe committed config no longer matches deploy/security-headers.mjs. ` +
        'Edit the source, not the config, then run `npm run nginx`.',
    );
    process.exit(1);
  }
  console.log(`nginx config matches deploy/security-headers.mjs (${SECURITY_HEADERS.length} headers)`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
