// B1c-1 Task 7's generator (committed by the final fix wave, item 11): writes src/provider/icon.ts from
// web/public/noc-mark.png (the owner's mark, 96 × 96 PNG). icon.ts is generated only — never edit it by hand; run
// `node extension/scripts/gen-icon.mjs` (from anywhere) after the mark changes. scripts/__tests__/gen-icon.test.mjs
// checks icon.ts is byte for byte this script's output; src/provider/__tests__/provider.test.ts checks the data URL
// decodes to exactly the PNG.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const PNG_PATH = join(here, '..', '..', 'web', 'public', 'noc-mark.png');
export const ICON_PATH = join(here, '..', 'src', 'provider', 'icon.ts');

/** icon.ts's full text for these PNG bytes: the base64 in 100-character lines. */
export function iconSource(png) {
  const lines = Buffer.from(png).toString('base64').match(/.{1,100}/g);
  return `/**
 * GENERATED by extension/scripts/gen-icon.mjs — never edit by hand: the Noctura mark, web/public/noc-mark.png (the
 * owner's logo, 96 × 96 PNG), as the data URL Wallet Standard requires for a wallet's icon (spec §1.1). No fetch:
 * the provider runs in the page and loads nothing. src/provider/__tests__/provider.test.ts checks it is that file.
 */
export const ICON = \`data:image/png;base64,\${[
${lines.map(l => `  '${l}',`).join('\n')}
].join('')}\` as const;
`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(ICON_PATH, iconSource(readFileSync(PNG_PATH)));
}
